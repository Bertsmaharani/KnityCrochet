"""
Модуль тестирования API на основе свойств (property-based testing).

Используется библиотека Schemathesis, которая автоматически
считывает OpenAPI-спецификацию, сгенерированную FastAPI, и формирует
большое количество тестовых запросов с различными комбинациями входных данных,
включая некорректные.

Цель — выявить ситуации, при которых сервер возвращает ошибку 500
(внутренняя ошибка), что свидетельствует о непредвиденном поведении
и необходимости доработки обработки ошибок.
"""
import schemathesis


# Загрузка OpenAPI-схемы из работающего экземпляра приложения.
# Перед запуском тестов сервер должен быть запущен командой:
# uvicorn app.main:app --port 8000
schema = schemathesis.from_uri("http://127.0.0.1:8000/openapi.json")


@schema.parametrize()
def test_api(case):
    """
    Универсальный тест для всех эндпоинтов API.

    Schemathesis автоматически создаёт отдельный тестовый случай
    для каждой конечной точки и каждого HTTP-метода, генерируя
    валидные и невалидные входные данные.
    """
    response = case.call()
    # Проверка соответствия ответа заявленной в схеме спецификации
    case.validate_response(response)