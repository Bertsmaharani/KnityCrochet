"""
Модуль конфигурации приложения.

Обеспечивает централизованное хранение параметров, необходимых для работы системы.
Значения считываются из файла .env, что позволяет отделить конфиденциальные данные
от исходного кода и упростить развёртывание проекта в различных средах.
"""
from pydantic_settings import BaseSettings


class Settings(BaseSettings):
    """
    Класс настроек приложения.

    Наследуется от BaseSettings, что обеспечивает автоматическое чтение значений
    из переменных окружения и файла .env.
    """

    # Строка подключения к СУБД PostgreSQL
    database_url: str

    # Секретный ключ для подписи JWT-токенов
    secret_key: str

    # Алгоритм шифрования токена (стандарт — HS256)
    algorithm: str = "HS256"

    # Время жизни токена доступа (в минутах)
    access_token_expire_minutes: int = 60

    class Config:
        # Указывает источник значений — файл .env в корне проекта
        env_file = ".env"


# Экземпляр настроек, используемый во всех модулях приложения
settings = Settings()